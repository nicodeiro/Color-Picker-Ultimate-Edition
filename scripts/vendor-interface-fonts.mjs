import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdtemp, mkdir, readFile, readdir, rm, copyFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { basename, dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PACKAGE_VERSION = '5.3.0';
const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = resolve(SCRIPT_DIR, '..');
const OUTPUT_ROOT = join(PROJECT_ROOT, 'assets', 'fonts', 'interface');
const CSS_OUTPUT = join(PROJECT_ROOT, 'fonts.css');

const VARIABLE = ['wght.css'];

const FONT_PACKAGES = [
    ['roboto-flex', '@fontsource-variable/roboto-flex', VARIABLE],
    ['roboto-mono', '@fontsource-variable/roboto-mono', VARIABLE]
];

function sha256(buffer) {
    return createHash('sha256').update(buffer).digest('hex');
}

async function copyWithParents(source, target) {
    await mkdir(dirname(target), { recursive: true });
    await copyFile(source, target);
}

function referencedFontFiles(css) {
    return [...css.matchAll(/url\((?:['"])?\.\/files\/([^)'"\s]+)(?:['"])?\)/gu)]
        .map((match) => match[1]);
}

function keepSupportedSubsets(css) {
    const blocks = [...css.matchAll(/\/\*\s*([^*]+?)\s*\*\/\s*@font-face\s*\{[^}]*\}/gu)];
    const kept = blocks
        .filter((match) => /(?:^|-)(?:latin|cyrillic)(?:-ext)?(?:-|$)/u.test(match[1]))
        .map((match) => match[0].trim());
    if (!kept.length) {
        throw new Error('Font CSS does not expose a Latin or Cyrillic subset');
    }
    return `${kept.join('\n\n')}\n`.replace(
        /,\s*url\([^)]*\.woff\)\s*format\(['"]woff['"]\)/gu,
        ''
    );
}

async function vendorPackage(tempRoot, [slug, packageName, requestedCss]) {
    const packageSpec = `${packageName}@${PACKAGE_VERSION}`;
    const packJson = execFileSync(
        'npm',
        ['pack', packageSpec, '--json', '--pack-destination', tempRoot],
        { encoding: 'utf8' }
    );
    const [packResult] = JSON.parse(packJson);
    const archivePath = join(tempRoot, packResult.filename);
    const extractRoot = join(tempRoot, `extract-${slug}`);
    await mkdir(extractRoot, { recursive: true });
    execFileSync('tar', ['-xzf', archivePath, '-C', extractRoot]);

    const sourceRoot = join(extractRoot, 'package');
    const targetRoot = join(OUTPUT_ROOT, slug);
    await mkdir(targetRoot, { recursive: true });

    const availableNames = new Set(await readdir(sourceRoot));
    const cssFiles = requestedCss.filter((name) => availableNames.has(name));
    if (!cssFiles.length) {
        throw new Error(`${packageSpec} does not contain any requested CSS file`);
    }

    const copied = [];
    const licenseTarget = join(targetRoot, 'LICENSE');
    const licenseText = (await readFile(join(sourceRoot, 'LICENSE'), 'utf8')).replaceAll('\r\n', '\n');
    await writeFile(licenseTarget, licenseText, 'utf8');
    copied.push(licenseTarget);

    const metadataTarget = join(targetRoot, 'metadata.json');
    await copyWithParents(join(sourceRoot, 'metadata.json'), metadataTarget);
    copied.push(metadataTarget);

    for (const cssName of cssFiles) {
        const cssSource = join(sourceRoot, cssName);
        const css = keepSupportedSubsets(await readFile(cssSource, 'utf8'));
        const cssTarget = join(targetRoot, cssName);
        await writeFile(cssTarget, css, 'utf8');
        copied.push(cssTarget);

        for (const fontFile of referencedFontFiles(css)) {
            const source = join(sourceRoot, 'files', fontFile);
            const target = join(targetRoot, 'files', fontFile);
            await copyWithParents(source, target);
            copied.push(target);
        }
    }

    const uniqueFiles = [...new Set(copied)].sort();
    const checksums = [];
    for (const file of uniqueFiles) {
        const bytes = await readFile(file);
        checksums.push({
            path: relative(PROJECT_ROOT, file),
            bytes: bytes.byteLength,
            sha256: sha256(bytes)
        });
    }

    return {
        slug,
        packageName,
        packageVersion: PACKAGE_VERSION,
        npmIntegrity: packResult.integrity,
        npmShasum: packResult.shasum,
        cssFiles,
        checksums
    };
}

async function main() {
    const tempRoot = await mkdtemp(join(tmpdir(), 'color-picker-fonts-'));
    await rm(OUTPUT_ROOT, { recursive: true, force: true });
    await mkdir(OUTPUT_ROOT, { recursive: true });

    try {
        const sources = [];
        for (const fontPackage of FONT_PACKAGES) {
            process.stdout.write(`Vendoring ${fontPackage[1]}…\n`);
            sources.push(await vendorPackage(tempRoot, fontPackage));
        }

        const imports = [
            '/* Generated by scripts/vendor-interface-fonts.mjs. All imports are local. */',
            ...sources.flatMap((source) => source.cssFiles.map((cssFile) => (
                `@import url("assets/fonts/interface/${source.slug}/${cssFile}");`
            ))),
            ''
        ].join('\n');
        await writeFile(CSS_OUTPUT, imports, 'utf8');

        const sourceDocument = [
            '# Interface font provenance',
            '',
            'Roboto Flex and Roboto Mono are vendored locally as the fixed product typography.',
            'Roboto Flex is used for interface and display text; Roboto Mono is reserved for HEX, RGB and HSL data.',
            'No font is downloaded at runtime. Package tarballs were resolved at the pinned version below.',
            'Both packages are redistributed under the SIL Open Font License 1.1; their full licence text is stored beside the font files.',
            'Only the upstream Latin, Latin Extended, Cyrillic and Cyrillic Extended WOFF2 files are packaged; the font binaries are copied unchanged.',
            'Japanese and Chinese text deliberately falls back to the operating-system script fonts declared in `styles.css`.',
            '',
            `- Fontsource package version: \`${PACKAGE_VERSION}\``,
            '- Package registry: <https://www.npmjs.com/org/fontsource>',
            '- Fontsource source repository: <https://github.com/fontsource/font-files>',
            '',
            ...sources.flatMap((source) => [
                `## ${source.packageName}`,
                '',
                `- Package: \`${source.packageName}@${source.packageVersion}\``,
                `- npm integrity: \`${source.npmIntegrity}\``,
                `- npm shasum: \`${source.npmShasum}\``,
                '- License: copied to the package folder as `LICENSE`.',
                '',
                '| Local file | Bytes | SHA-256 |',
                '| --- | ---: | --- |',
                ...source.checksums.map((file) => (
                    `| \`${file.path}\` | ${file.bytes.toLocaleString('en-US')} | \`${file.sha256}\` |`
                )),
                ''
            ])
        ].join('\n');
        await writeFile(join(OUTPUT_ROOT, 'SOURCE.md'), sourceDocument, 'utf8');
    } finally {
        await rm(tempRoot, { recursive: true, force: true });
    }
}

await main();
